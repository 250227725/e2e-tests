#!/bin/bash

# Проверяем, что передан путь к папке с тестами
if [ -z "$1" ]; then
    echo "Ошибка: Не указан путь к папке с проектом тестов"
    echo "Использование: $0 <путь_к_папке_тестов>"
    exit 1
fi

TEST_DIR="$1"

# Переходим в указанную папку с тестами
cd "$TEST_DIR" || { echo "Ошибка: Папка '$TEST_DIR' не найдена"; exit 1; }

# Запускаем тесты Playwright
# Используем CI=true, чтобы вывод в консоль был чистым и без интерактивных меню
CI=true npx playwright test

# Возвращаем статус выполнения (0 - успех, >0 - ошибка)
exit $?
